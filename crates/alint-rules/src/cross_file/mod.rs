/// Hard ceiling for values one cross-file extraction may materialize. Exceeding
/// it is a fail-loud analysis failure, never a truncated policy pass.
pub(crate) const MAX_EXTRACTED_VALUES: usize = 10_000;
const MAX_SYNTAX_PHYSICAL_LINES: usize = 100_000;

fn enforce_syntax_line_limit(text: &str, format: &str) -> std::result::Result<(), String> {
    let mut lines = usize::from(!text.is_empty() && !text.ends_with('\n'));
    for byte in text.bytes() {
        if byte == b'\n' {
            lines += 1;
            if lines > MAX_SYNTAX_PHYSICAL_LINES {
                return Err(format!(
                    "{format} exceeds the {MAX_SYNTAX_PHYSICAL_LINES}-line safety limit"
                ));
            }
        }
    }
    Ok(())
}

/// Capture-group-1 byte ranges for a target regex. Dockerfile `FROM`, Python
/// `__version__`, extensionless Rust toolchain, and Gemfile selectors receive
/// syntax-aware filtering so inert strings and heredocs cannot impersonate declarations.
#[derive(Debug)]
pub(crate) struct RegexCaptureRanges {
    pub(crate) any_match: bool,
    pub(crate) had_group: bool,
    pub(crate) ranges: Vec<Range<usize>>,
}

pub(crate) fn target_regex_capture_ranges(
    path: &Path,
    text: &str,
    pattern: &str,
) -> std::result::Result<RegexCaptureRanges, String> {
    let regex = regex::Regex::new(pattern)
        .map_err(|error| format!("invalid target regex `{pattern}`: {error}"))?;
    let name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("");
    let mut expected_capture = None;
    let allowed_lines = if name.starts_with("Dockerfile") && pattern.contains("FROM") {
        Some(crate::pinned_references::dockerfile_from_lines(text)?)
    } else if path.extension().and_then(|ext| ext.to_str()) == Some("py")
        && pattern.contains("__version__")
    {
        Some(python_top_level_code_lines(text)?)
    } else if name == "rust-toolchain" && pattern.contains("channel") {
        let (lines, expected) = rust_toolchain_code_lines(text)?;
        expected_capture = expected;
        lines
    } else if name == "Gemfile" && pattern.contains("ruby") {
        Some(ruby_code_lines(text)?)
    } else {
        None
    };
    let mut next_newline = text
        .match_indices('\n')
        .map(|(offset, _)| offset)
        .peekable();
    let mut line = 1usize;
    let mut any_match = false;
    let mut had_group = false;
    let mut ranges = Vec::new();
    let mut accepted_matches = 0usize;
    for captures in regex.captures_iter(text) {
        let start = captures.get(0).map_or(0, |matched| matched.start());
        while next_newline.peek().is_some_and(|offset| *offset < start) {
            next_newline.next();
            line += 1;
        }
        if allowed_lines
            .as_ref()
            .is_some_and(|lines| lines.binary_search(&line).is_err())
        {
            continue;
        }
        let group = captures.get(1);
        if expected_capture
            .as_deref()
            .is_some_and(|expected| group.is_none_or(|group| group.as_str() != expected))
        {
            continue;
        }
        accepted_matches += 1;
        if accepted_matches > MAX_EXTRACTED_VALUES {
            return Err(format!(
                "target regex selected more than the {MAX_EXTRACTED_VALUES}-value safety limit"
            ));
        }
        any_match = true;
        let Some(group) = group else {
            continue;
        };
        had_group = true;
        ranges.push(group.range());
    }
    Ok(RegexCaptureRanges {
        any_match,
        had_group,
        ranges,
    })
}

#[derive(Clone, Copy)]
struct PythonQuote {
    delimiter: u8,
    triple: bool,
}

/// Lines that begin in top-level Python code rather than a string, comment
/// continuation, or bracketed expression. This is a lexical guard for the
/// bundle's column-zero `__version__` regex, not a general Python parser.
fn python_top_level_code_lines(text: &str) -> std::result::Result<Vec<usize>, String> {
    enforce_syntax_line_limit(text, "Python source")?;
    let mut lines = Vec::new();
    let mut quote: Option<PythonQuote> = None;
    let mut bracket_depth = 0usize;
    let mut explicit_continuation = false;

    for (index, physical) in text.split_inclusive('\n').enumerate() {
        if quote.is_none() && bracket_depth == 0 && !explicit_continuation {
            lines.push(index + 1);
        }
        let bytes = physical.as_bytes();
        let mut offset = 0usize;
        let mut last_code_non_whitespace = None;
        while offset < bytes.len() {
            if let Some(active) = quote {
                if bytes[offset] == b'\\' {
                    offset = (offset + 2).min(bytes.len());
                    continue;
                }
                if active.triple
                    && offset + 2 < bytes.len()
                    && bytes[offset] == active.delimiter
                    && bytes[offset + 1] == active.delimiter
                    && bytes[offset + 2] == active.delimiter
                {
                    quote = None;
                    offset += 3;
                    continue;
                }
                if !active.triple && bytes[offset] == active.delimiter {
                    quote = None;
                }
                offset += 1;
                continue;
            }

            let byte = bytes[offset];
            if byte == b'#' {
                break;
            }
            if matches!(byte, b'\'' | b'"') {
                let triple = offset + 2 < bytes.len()
                    && bytes[offset + 1] == byte
                    && bytes[offset + 2] == byte;
                quote = Some(PythonQuote {
                    delimiter: byte,
                    triple,
                });
                offset += if triple { 3 } else { 1 };
                continue;
            }
            match byte {
                b'(' | b'[' | b'{' => bracket_depth += 1,
                b')' | b']' | b'}' => bracket_depth = bracket_depth.saturating_sub(1),
                _ => {}
            }
            if !byte.is_ascii_whitespace() {
                last_code_non_whitespace = Some(byte);
            }
            offset += 1;
        }
        explicit_continuation =
            quote.is_none() && bracket_depth == 0 && last_code_non_whitespace == Some(b'\\');
    }
    Ok(lines)
}

fn rust_toolchain_code_lines(
    text: &str,
) -> std::result::Result<(Option<Vec<usize>>, Option<String>), String> {
    enforce_syntax_line_limit(text, "rust-toolchain TOML")?;
    let trimmed = text.trim();
    if trimmed.lines().count() <= 1 && !trimmed.contains(['=', '[', ']', '"', '\'']) {
        // The legacy rust-toolchain form is one bare token; the rule's
        // whole-file regex remains the exact grammar and needs no line filter.
        return Ok((None, None));
    }
    let parsed: toml::Value =
        toml::from_str(text).map_err(|error| format!("invalid rust-toolchain TOML: {error}"))?;
    let expected = parsed
        .get("toolchain")
        .and_then(|toolchain| toolchain.get("channel"))
        .and_then(toml::Value::as_str)
        .map(str::to_owned);
    let code_lines = toml_code_lines(text);
    Ok((
        Some(rust_toolchain_channel_lines(text, &code_lines)),
        expected,
    ))
}

#[derive(Clone, Copy)]
enum TomlQuote {
    Basic { multiline: bool },
    Literal { multiline: bool },
}

/// Physical lines that start outside TOML strings. The document is parsed
/// before this scanner is used, so this only locates syntax already accepted by
/// the TOML parser; it does not attempt independent validation.
fn toml_code_lines(text: &str) -> Vec<usize> {
    let mut lines = Vec::new();
    let mut quote = None;
    for (index, physical) in text.split_inclusive('\n').enumerate() {
        if quote.is_none() {
            lines.push(index + 1);
        }
        let bytes = physical.as_bytes();
        let mut offset = 0usize;
        while offset < bytes.len() {
            match quote {
                Some(TomlQuote::Basic { multiline }) => {
                    if bytes[offset] == b'\\' {
                        offset = (offset + 2).min(bytes.len());
                    } else if multiline
                        && bytes.get(offset..offset + 3) == Some(b"\"\"\"".as_slice())
                    {
                        quote = None;
                        offset += 3;
                    } else if !multiline && bytes[offset] == b'"' {
                        quote = None;
                        offset += 1;
                    } else {
                        offset += 1;
                    }
                }
                Some(TomlQuote::Literal { multiline }) => {
                    if multiline && bytes.get(offset..offset + 3) == Some(b"'''".as_slice()) {
                        quote = None;
                        offset += 3;
                    } else if !multiline && bytes[offset] == b'\'' {
                        quote = None;
                        offset += 1;
                    } else {
                        offset += 1;
                    }
                }
                None => match bytes[offset] {
                    b'#' => break,
                    b'"' => {
                        let multiline = bytes.get(offset..offset + 3) == Some(b"\"\"\"".as_slice());
                        quote = Some(TomlQuote::Basic { multiline });
                        offset += if multiline { 3 } else { 1 };
                    }
                    b'\'' => {
                        let multiline = bytes.get(offset..offset + 3) == Some(b"'''".as_slice());
                        quote = Some(TomlQuote::Literal { multiline });
                        offset += if multiline { 3 } else { 1 };
                    }
                    _ => offset += 1,
                },
            }
        }
    }
    lines
}

fn rust_toolchain_channel_lines(text: &str, code_lines: &[usize]) -> Vec<usize> {
    let mut in_toolchain = false;
    let mut channel_lines = Vec::new();
    for (index, line) in text.lines().enumerate() {
        let line_number = index + 1;
        if code_lines.binary_search(&line_number).is_err() {
            continue;
        }
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            let header = trimmed
                .split_once('#')
                .map_or(trimmed, |(header, _)| header)
                .trim();
            in_toolchain = header == "[toolchain]";
            continue;
        }
        if in_toolchain
            && trimmed
                .strip_prefix("channel")
                .is_some_and(|rest| rest.trim_start().starts_with('='))
        {
            channel_lines.push(line_number);
        }
    }
    channel_lines
}

#[derive(Clone, Copy)]
enum RubyQuote {
    Simple {
        delimiter: u8,
        escaped: bool,
    },
    Percent {
        open: u8,
        close: u8,
        depth: usize,
        escaped: bool,
    },
}

/// Lines that start outside Ruby strings and heredoc bodies. This deliberately
/// recognizes only lexical constructs needed to keep a Gemfile's top-level
/// `ruby` directive distinct from inert embedded text.
// One state machine must carry quote, heredoc, block-comment, and delimiter
// state together; splitting it would duplicate or desynchronize transitions.
#[allow(clippy::too_many_lines)]
fn ruby_code_lines(text: &str) -> std::result::Result<Vec<usize>, String> {
    enforce_syntax_line_limit(text, "Gemfile")?;
    let mut lines = Vec::new();
    let mut quote = None;
    let mut heredocs: Vec<(String, bool)> = Vec::new();
    let mut block_comment = false;

    for (index, physical) in text.split_inclusive('\n').enumerate() {
        let line = physical
            .strip_suffix('\n')
            .unwrap_or(physical)
            .strip_suffix('\r')
            .unwrap_or_else(|| physical.strip_suffix('\n').unwrap_or(physical));
        if let Some((delimiter, allow_indent)) = heredocs.first() {
            let candidate = if *allow_indent {
                line.trim_start()
            } else {
                line
            };
            if candidate == delimiter {
                heredocs.remove(0);
            }
            continue;
        }
        if block_comment {
            if line
                .strip_prefix("=end")
                .is_some_and(|rest| rest.is_empty() || rest.starts_with(char::is_whitespace))
            {
                block_comment = false;
            }
            continue;
        }
        if quote.is_none() {
            if line == "__END__" {
                break;
            }
            if line
                .strip_prefix("=begin")
                .is_some_and(|rest| rest.is_empty() || rest.starts_with(char::is_whitespace))
            {
                block_comment = true;
                continue;
            }
        }

        if quote.is_none() {
            lines.push(index + 1);
        }
        let bytes = physical.as_bytes();
        let mut offset = 0usize;
        while offset < bytes.len() {
            match quote {
                Some(RubyQuote::Simple { delimiter, escaped }) => {
                    if escaped {
                        quote = Some(RubyQuote::Simple {
                            delimiter,
                            escaped: false,
                        });
                    } else if bytes[offset] == b'\\' {
                        quote = Some(RubyQuote::Simple {
                            delimiter,
                            escaped: true,
                        });
                    } else if bytes[offset] == delimiter {
                        quote = None;
                    }
                    offset += 1;
                }
                Some(RubyQuote::Percent {
                    open,
                    close,
                    mut depth,
                    escaped,
                }) => {
                    if escaped {
                        quote = Some(RubyQuote::Percent {
                            open,
                            close,
                            depth,
                            escaped: false,
                        });
                    } else if bytes[offset] == b'\\' {
                        quote = Some(RubyQuote::Percent {
                            open,
                            close,
                            depth,
                            escaped: true,
                        });
                    } else if open != close && bytes[offset] == open {
                        depth += 1;
                        quote = Some(RubyQuote::Percent {
                            open,
                            close,
                            depth,
                            escaped: false,
                        });
                    } else if bytes[offset] == close {
                        depth -= 1;
                        quote = (depth != 0).then_some(RubyQuote::Percent {
                            open,
                            close,
                            depth,
                            escaped: false,
                        });
                    }
                    offset += 1;
                }
                None => {
                    let byte = bytes[offset];
                    if byte == b'#' {
                        break;
                    }
                    if matches!(byte, b'\'' | b'"' | b'`') {
                        quote = Some(RubyQuote::Simple {
                            delimiter: byte,
                            escaped: false,
                        });
                        offset += 1;
                        continue;
                    }
                    if byte == b'%' {
                        let mut delimiter_at = offset + 1;
                        if bytes.get(delimiter_at).is_some_and(|kind| {
                            matches!(kind, b'q' | b'Q' | b'w' | b'W' | b'x' | b'r' | b'i' | b'I')
                        }) {
                            delimiter_at += 1;
                        }
                        if let Some(&open) = bytes.get(delimiter_at)
                            && !open.is_ascii_alphanumeric()
                            && !open.is_ascii_whitespace()
                        {
                            let close = match open {
                                b'(' => b')',
                                b'[' => b']',
                                b'{' => b'}',
                                b'<' => b'>',
                                _ => open,
                            };
                            quote = Some(RubyQuote::Percent {
                                open,
                                close,
                                depth: 1,
                                escaped: false,
                            });
                            offset = delimiter_at + 1;
                            continue;
                        }
                    }
                    if bytes.get(offset..offset + 2) == Some(b"<<".as_slice()) {
                        let mut at = offset + 2;
                        let allow_indent = matches!(bytes.get(at), Some(b'-' | b'~'));
                        if allow_indent {
                            at += 1;
                        }
                        let quoted = bytes
                            .get(at)
                            .copied()
                            .filter(|byte| matches!(byte, b'\'' | b'"' | b'`'));
                        if quoted.is_some() {
                            at += 1;
                        }
                        let start = at;
                        while bytes
                            .get(at)
                            .is_some_and(|byte| byte.is_ascii_alphanumeric() || *byte == b'_')
                        {
                            at += 1;
                        }
                        if at > start
                            && quoted.is_none_or(|delimiter| bytes.get(at) == Some(&delimiter))
                        {
                            heredocs.push((
                                String::from_utf8_lossy(&bytes[start..at]).into_owned(),
                                allow_indent,
                            ));
                            offset = at + usize::from(quoted.is_some());
                            continue;
                        }
                    }
                    offset += 1;
                }
            }
        }
    }
    if quote.is_some() || !heredocs.is_empty() || block_comment {
        return Err("unterminated Ruby string, heredoc, or block comment in Gemfile".to_string());
    }
    Ok(lines)
}

#[derive(Debug)]
pub struct CrossFileRule {
    id: String,
    level: Level,
    policy_url: Option<String>,
    message: Option<String>,
    /// The source path (single-file mode) or the glob string (used
    /// for display in messages when `source_glob` is set).
    source_file: String,
    /// `Some` ⇒ glob-union source: `source_file` is the glob, and
    /// `source_values` unions the extracted values across every
    /// matching file. Set-relations only.
    source_glob: Option<Scope>,
    /// `Some` for value relations + `resolves`; `None` for `identical`.
    source_extract: Option<Extract>,
    /// `Some` for value relations + `identical`; `None` for `resolves`.
    targets: Option<Targets>,
    relation: Relation,
    /// Ordered transform list (empty = no normalization).
    normalize: Vec<Normalize>,
    allow_missing: bool,
    skip_header_lines: usize,
    /// `relation: registered` only: a template over the matched member path
    /// supporting `{path}`, `{dir}`, `{basename}`, `{stem}`, `{ext}`, and
    /// `{parent_name}`. The rendered value is looked for (and, on fix, added) in
    /// the target list. `None` uses `{path}` (the matched path).
    register_as: Option<String>,
    /// The `sync_from` fixer: on `relation: identical` a whole-file `SyncFromFixer`
    /// (mirror the source), on `relation: equals` a `CrossFileValueFixer`
    /// (propagate the source's extracted scalar into each target's node). `None`
    /// for every other relation and when no `fix:` block is set. Boxed so the two
    /// apply-based fixers share one field.
    fixer: Option<Box<dyn Fixer>>,
}

impl Rule for CrossFileRule {
    alint_core::rule_common_impl!();

    fn requires_full_index(&self) -> bool {
        // Cross-file: the source and every target may live
        // anywhere in the tree; never `--changed`-scoped.
        true
    }

    fn visit_sensitive_paths(
        &self,
        explicit: bool,
        ctx: &Context<'_>,
        visit: &mut dyn FnMut(&Path),
    ) {
        let source_sensitive = explicit
            || self
                .source_extract
                .as_ref()
                .is_some_and(Extract::redacts_by_default);
        if source_sensitive {
            if let Some(scope) = &self.source_glob {
                for entry in ctx.index.files() {
                    if scope.matches(&entry.path, ctx.index) {
                        visit(&entry.path);
                    }
                }
            } else {
                visit(Path::new(&self.source_file));
            }
        }

        match &self.targets {
            Some(Targets::Glob { scope, extract, .. })
                if explicit || extract.as_ref().is_some_and(Extract::redacts_by_default) =>
            {
                for entry in ctx.index.files() {
                    if scope.matches(&entry.path, ctx.index) {
                        visit(&entry.path);
                    }
                }
            }
            Some(Targets::List(targets)) => {
                for target in targets {
                    if explicit
                        || target
                            .extract
                            .as_ref()
                            .is_some_and(Extract::redacts_by_default)
                    {
                        visit(Path::new(&target.file));
                    }
                }
            }
            _ => {}
        }
    }

    fn fixer(&self) -> Option<&dyn Fixer> {
        self.fixer.as_deref()
    }

    fn evaluate(&self, ctx: &Context<'_>) -> Result<Vec<Violation>> {
        let findings = self.evaluate_impl(ctx);
        #[cfg(feature = "shadow-ir")]
        shadow::assert_equals_matches(self, ctx, &findings);
        Ok(findings)
    }

    fn uses_relations(&self) -> bool {
        // Only the R4 shadow consumes the relation layer, and only when the
        // test/corpus feature is on. Production stays on the direct read path.
        cfg!(feature = "shadow-ir") && self.relation == Relation::Equals
    }
}

/// Build the `sync_from` fixer for a `cross_file` rule, or reject an unsupported
/// `fix:` block. `sync_from` is the only fix op `cross_file` supports; its behavior
/// depends on the relation: on `identical` it is a WHOLE-FILE mirror
/// (`SyncFromFixer`), on `equals` it PROPAGATES the source's single extracted
/// scalar into each target's node (`CrossFileValueFixer`). A value relation with a
/// preserved header, or a set / resolves relation, has no single "correct" whole
/// value/bytes to write and is rejected.
#[allow(clippy::too_many_arguments)] // a config-parser dispatch: the shape inputs travel together
fn build_sync_from_fixer(
    fix: Option<&FixSpec>,
    relation: Relation,
    skip_header_lines: usize,
    source_file: &str,
    single_file_source: bool,
    source_extract: Option<&Extract>,
    targets: Option<&Targets>,
    normalize: &[Normalize],
    cfg: &impl Fn(String) -> Error,
) -> Result<Option<Box<dyn Fixer>>> {
    match fix {
        None => Ok(None),
        Some(FixSpec::SyncFrom { sync_from }) => {
            let tier = sync_from.applicability.unwrap_or(Applicability::Unsafe);
            match relation {
                Relation::Identical => {
                    if skip_header_lines != 0 {
                        return Err(cfg(
                            "`sync_from` cannot preserve the target's header: it copies the \
                             whole source file, which would overwrite the `skip_header_lines` \
                             header the rule deliberately ignores. Drop `skip_header_lines`, or \
                             fix the drift by hand."
                                .into(),
                        ));
                    }
                    // `identical` always has a single-file source (the glob-union
                    // form is rejected earlier for non-set relations); assert it.
                    debug_assert!(
                        single_file_source,
                        "identical must have a single-file source"
                    );
                    Ok(Some(Box::new(SyncFromFixer::new(
                        PathBuf::from(source_file),
                        tier,
                    ))))
                }
                Relation::Equals => {
                    // Value propagation: rewrite each target's extracted node to the
                    // source's single scalar. `validate_shape` guarantees a value
                    // relation has `source.extract` + `targets` with `extract`.
                    let source_extract = source_extract
                        .ok_or_else(
                            || cfg("`sync_from` on `equals` needs `source.extract`".into()),
                        )?
                        .clone();
                    let (value_targets, target_matches) = build_value_targets(targets, cfg)?;
                    Ok(Some(Box::new(
                        CrossFileValueFixer::new(
                            PathBuf::from(source_file),
                            source_extract,
                            value_targets,
                            normalize.to_vec(),
                            tier,
                        )
                        .with_target_matches(target_matches),
                    )))
                }
                other => Err(cfg(format!(
                    "`sync_from` supports `relation: identical` (mirror the whole file) or \
                     `equals` (propagate one value); `{other:?}` is a set / resolves relation \
                     with no single value to propagate"
                ))),
            }
        }
        Some(FixSpec::CreateAndRegister {
            create_and_register,
        }) => {
            if relation != Relation::Registered {
                return Err(cfg(format!(
                    "`create_and_register` requires `relation: registered`; `{relation:?}` \
                     has no member list to register into"
                )));
            }
            let tier = create_and_register
                .applicability
                .unwrap_or(Applicability::Unsafe);
            let register_targets = build_register_targets(targets, cfg)?;
            // Optional `content`/`content_from` = the create half (a missing NAMED
            // member's file). Both absent = register-only. Content on a GLOB source
            // is inert (a glob never yields a missing member), so it is rejected.
            let content = match (
                &create_and_register.content,
                &create_and_register.content_from,
            ) {
                (None, None) => None,
                (Some(_), Some(_)) => {
                    return Err(cfg(
                        "`create_and_register`: `content` and `content_from` are mutually exclusive"
                            .into(),
                    ));
                }
                (inline, from) => {
                    if !single_file_source {
                        return Err(cfg(
                            "`create_and_register` `content`/`content_from` (the create half) \
                             applies only to a NAMED `source.file`; a `source.files` glob never \
                             yields a MISSING member to create -- remove it (register-only)"
                                .into(),
                        ));
                    }
                    Some(match (inline, from) {
                        (Some(s), None) => alint_core::ContentSourceSpec::Inline(s.clone()),
                        (None, Some(p)) => alint_core::ContentSourceSpec::File(p.clone()),
                        _ => unreachable!("XOR checked above"),
                    })
                }
            };
            Ok(Some(Box::new(CreateAndRegisterFixer::new(
                register_targets,
                content,
                tier,
            ))))
        }
        Some(other) => Err(cfg(format!(
            "fix.{} is not compatible with cross_file (only `sync_from` and `create_and_register`)",
            other.op_name()
        ))),
    }
}

/// Resolve the per-target ARRAY extract for `create_and_register`: each target
/// extract must be `Structured(fmt, "$.path[*]")` -- the same element query the
/// check uses -- with the trailing `[*]` stripped to the ARRAY path the fixer
/// appends into. A `lines` / `whole_file` / regex extract, or one that does not
/// select array elements with `[*]`, is rejected at load.
fn build_register_targets(
    targets: Option<&Targets>,
    cfg: &impl Fn(String) -> Error,
) -> Result<ValueTargets> {
    let array_extract = |ex: Option<&Extract>, what: &str| -> Result<Extract> {
        match ex {
            Some(Extract::Structured(extract)) => {
                let query = &extract.query;
                let array_query = query.strip_suffix("[*]").ok_or_else(|| {
                    cfg(format!(
                        "`relation: registered` {what} extract must select the array ELEMENTS \
                         with a trailing `[*]` (e.g. `$.workspace.members[*]`), so the check \
                         sees each element and the fix can locate the array; got `{query}`"
                    ))
                })?;
                // The array path must be STATIC -- exactly ONE array. A residual
                // wildcard (`$..members[*]`, `$.a[*].members[*]`) or a filter makes
                // the check UNION elements across several arrays while the fixer
                // appends to only the FIRST match -- silently the wrong array (audit
                // A#2/B#5). Reject any leftover `*` / `..` / `?`.
                if array_query.contains('*')
                    || array_query.contains("..")
                    || array_query.contains('?')
                {
                    return Err(cfg(format!(
                        "`relation: registered` {what} extract must select ONE array with a \
                         STATIC path plus a trailing `[*]` (e.g. `$.workspace.members[*]`); \
                         `{query}` has an extra wildcard / recursive-descent / filter, which \
                         would append to the wrong array"
                    )));
                }
                Extract::structured(extract.format, array_query)
                    .map_err(|e| cfg(format!("invalid registered array extract: {e}")))
            }
            _ => Err(cfg(format!(
                "`relation: registered` {what} needs a STRUCTURED extract naming the list, \
                 e.g. `{{ toml: \"$.workspace.members[*]\" }}`"
            ))),
        }
    };
    match targets {
        Some(Targets::Glob {
            extract, matches, ..
        }) => {
            if matches.is_some() {
                return Err(cfg(
                    "`targets.matches` is not supported by `relation: registered`".into(),
                ));
            }
            Ok(ValueTargets::Glob(array_extract(
                extract.as_ref(),
                "the `targets.files` glob",
            )?))
        }
        Some(Targets::List(list)) => {
            let mut out = Vec::with_capacity(list.len());
            for target in list {
                if target.matches.is_some() {
                    return Err(cfg(
                        "`targets.matches` is not supported by `relation: registered`".into(),
                    ));
                }
                let e = array_extract(
                    target.extract.as_ref(),
                    &format!("target `{}`", target.file),
                )?;
                out.push((PathBuf::from(&target.file), e));
            }
            Ok(ValueTargets::List(out))
        }
        None => Err(cfg("`relation: registered` needs `targets`".into())),
    }
}

/// Resolve the per-target extract for value propagation. A target `extract` must be
/// `Structured` (a `JSONPath` over a parsed format -- rewrite the located node) or
/// `Regex` (rewrite each capture group 1); a `lines` / `whole_file` extract has no
/// single scalar to set and is rejected at load.
fn build_value_targets(
    targets: Option<&Targets>,
    cfg: &impl Fn(String) -> Error,
) -> Result<(ValueTargets, ValueTargetMatches)> {
    let unsupported = |what: &str| {
        cfg(format!(
            "`sync_from` on `equals` needs a STRUCTURED (toml/json/yaml/xml/ini/hcl/dotenv/\
             properties JSONPath) or REGEX target extract; {what} has a lines/whole-file extract, \
             which has no single value to set."
        ))
    };
    // A propagation target's extract must be Structured or Regex.
    let value_extract = |ex: Option<&Extract>, what: &str| -> Result<Extract> {
        match ex {
            Some(e @ (Extract::Structured(..) | Extract::Regex(_))) => Ok(e.clone()),
            _ => Err(unsupported(what)),
        }
    };
    match targets {
        Some(Targets::Glob {
            extract, matches, ..
        }) => Ok((
            ValueTargets::Glob(value_extract(extract.as_ref(), "the `targets.files` glob")?),
            ValueTargetMatches::Glob(matches.clone()),
        )),
        Some(Targets::List(list)) => {
            let mut out = Vec::with_capacity(list.len());
            let mut filters = Vec::with_capacity(list.len());
            for target in list {
                let extract = value_extract(
                    target.extract.as_ref(),
                    &format!("target `{}`", target.file),
                )?;
                let path = PathBuf::from(&target.file);
                out.push((path.clone(), extract));
                filters.push((path, target.matches.clone()));
            }
            Ok((ValueTargets::List(out), ValueTargetMatches::List(filters)))
        }
        None => Err(cfg("`sync_from` on `equals` needs `targets`".into())),
    }
}

